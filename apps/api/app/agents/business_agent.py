"""Business Agent — structured business plan / market analysis.

Produces a plan (summary, market, customers, revenue model, risks, next
steps) from the command brief via the AI provider chain, with any research
memories the orchestrator found included as context. The plan is saved as a
`reports` row (kind="business") and verified by re-reading it.

Honesty rule: every number in an AI-generated plan is an AI ESTIMATE, not a
verified fact — the result text and the report both say so explicitly.
"""
from datetime import datetime, timezone

from sqlalchemy.orm import Session

from .. import ai
from ..models import Report, Task
from .base import BaseAgent

ESTIMATE_NOTICE = (
    "Note: all figures in this plan are estimates generated by the AI from the brief"
    " (plus any saved research in context) — they are NOT verified market data."
)

_SECTIONS = "1) Summary 2) Market 3) Customers 4) Revenue model 5) Risks 6) Next steps"


class BusinessAgent(BaseAgent):
    key = "business"
    name = "Business Agent"

    def run(self, db: Session, task: Task, context: dict) -> dict:
        brief = task.description.strip()
        memories = context.get("memories", [])
        memory_block = ""
        research_hits = [m for m in memories if m.get("kind") == "research"]
        if research_hits:
            memory_block = "\n\nSaved research to take into account:\n" + "\n".join(
                f"- {m['title']}: {m['content'][:400]}" for m in research_hits
            )
        prompt = (
            f"Business brief: {brief}{memory_block}\n\n"
            f"Write a structured business plan with exactly these sections: {_SECTIONS}. "
            "Where you give numbers, mark them clearly as estimates."
        )
        plan = ai.chat(
            prompt,
            system="You are the PERSONAL OS Business Agent. Produce practical business plans. Label every figure as an estimate; never present invented numbers as verified facts.",
        )
        if not plan or not plan.strip():
            msg = "AI provider returned an empty business plan."
            return {"result": None, "verified": False, "error": msg, "logs": [msg]}

        now = datetime.now(timezone.utc)
        content = f"Business plan — {brief[:120]}\n\n{plan}\n\n{ESTIMATE_NOTICE}"
        report = Report(
            kind="business",
            title=f"Business Plan — {now:%Y-%m-%d %H:%M UTC}",
            content=content,
            data={"brief": brief, "research_memories_used": len(research_hits), "figures_are_estimates": True},
        )
        db.add(report)
        db.flush()
        saved = db.get(Report, report.id)
        if saved is None:
            msg = "Business report row could not be verified in the database."
            return {"result": None, "verified": False, "error": msg, "logs": [msg]}
        result = f"{content}\n\n(Saved as report {saved.id}.)"
        return {"result": result, "verified": True,
                "logs": [f"Business plan generated via AI provider '{ai.provider_name()}' with {len(research_hits)} research memory hit(s); report row {saved.id} verified."],
                "report_id": saved.id}
