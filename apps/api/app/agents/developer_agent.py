"""Developer Agent — creates REAL static website scaffolds on disk.

Operations:
  create — write index.html + style.css + script.js for the brief into
           <agent_workspace>/<slug>/ and verify on disk that the files
           exist and index.html contains "<html" and a <title>.
  review — list the projects under the workspace and summarize their
           files (names, sizes, index.html title) from the real files.

Safety: the agent only ever writes inside the workspace directory
(settings.agent_workspace_dir or apps/api/agent_workspace); the slug is
sanitized and the resolved path is checked to stay inside the workspace.
"""
import re
from pathlib import Path

from sqlalchemy.orm import Session

from ..config import settings
from ..models import Task
from .base import BaseAgent


def workspace_root() -> Path:
    if settings.agent_workspace_dir:
        return Path(settings.agent_workspace_dir)
    from ..config import BASE_DIR

    return BASE_DIR / "agent_workspace"


def slugify(text: str) -> str:
    cleaned = re.sub(
        r"(?i)\b(website|web site|site|app|banao|bana|create|make|build|for|a|an|the|page|landing)\b",
        " ",
        text,
    )
    slug = re.sub(r"[^a-z0-9]+", "-", cleaned.lower()).strip("-")
    return (slug or "my-site")[:60]


def site_title(text: str) -> str:
    cleaned = re.sub(
        r"(?i)\b(website|banao|bana|create|make|build|for)\b", " ", text
    )
    cleaned = re.sub(r"\s+", " ", cleaned).strip(" .:,-")
    return (cleaned or "My Website").title()[:80]


_INDEX = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{title}</title>
<link rel="stylesheet" href="style.css">
</head>
<body>
<header>
  <h1>{title}</h1>
  <p>{brief}</p>
</header>
<main>
  <section>
    <h2>Welcome</h2>
    <p>This starter site was generated by the PERSONAL OS Developer Agent. Edit this page to make it yours.</p>
    <button id="cta">Get started</button>
    <p id="msg"></p>
  </section>
</main>
<footer><p>&copy; {title}</p></footer>
<script src="script.js"></script>
</body>
</html>
"""

_CSS = """body { font-family: system-ui, sans-serif; margin: 0; background: #0f172a; color: #e2e8f0; }
header { padding: 3rem 1.5rem; text-align: center; background: #1e293b; }
main { max-width: 720px; margin: 2rem auto; padding: 0 1.5rem; }
button { background: #38bdf8; color: #082f49; border: 0; padding: .6rem 1.2rem; border-radius: .5rem; cursor: pointer; }
footer { text-align: center; padding: 2rem; color: #94a3b8; }
"""

_JS = """document.getElementById('cta').addEventListener('click', function () {
  document.getElementById('msg').textContent = 'Thanks for visiting — this site is ready to customize.';
});
"""


class DeveloperAgent(BaseAgent):
    key = "developer"
    name = "Developer Agent"

    def run(self, db: Session, task: Task, context: dict) -> dict:
        op = context.get("operation", "create")
        if op == "review":
            return self._review(db, task)
        if op != "create":
            msg = f"Developer agent does not support operation '{op}'."
            return {"result": None, "verified": False, "error": msg, "logs": [msg]}
        return self._create(db, task)

    def _create(self, db: Session, task: Task) -> dict:
        root = workspace_root()
        slug = slugify(task.description)
        target = (root / slug).resolve()
        if root.resolve() not in target.parents and target != root.resolve():
            msg = f"Refused: target path '{target}' is outside the agent workspace."
            return {"result": None, "verified": False, "error": msg, "logs": [msg]}
        title = site_title(task.description)
        brief = task.description.strip()[:200]
        files = {
            "index.html": _INDEX.format(title=title, brief=brief),
            "style.css": _CSS,
            "script.js": _JS,
        }
        target.mkdir(parents=True, exist_ok=True)
        for name, content in files.items():
            (target / name).write_text(content, encoding="utf-8")

        # Verify on disk — the files must really exist with real content.
        missing = [n for n in files if not (target / n).is_file() or (target / n).stat().st_size == 0]
        index_text = (target / "index.html").read_text(encoding="utf-8") if not missing else ""
        if missing or "<html" not in index_text.lower() or "<title>" not in index_text.lower():
            msg = f"Website files could not be verified on disk (missing/empty: {missing or 'index.html content check failed'})."
            return {"result": None, "verified": False, "error": msg, "logs": [msg]}
        listing = ", ".join(f"{n} ({(target / n).stat().st_size} bytes)" for n in files)
        result = (
            f"Website scaffold created at {target} — files: {listing}. "
            "Open index.html in a browser to view it. It has NOT been published anywhere."
        )
        return {"result": result, "verified": True,
                "logs": [f"Wrote and verified {len(files)} file(s) in {target}."]}

    def _review(self, db: Session, task: Task) -> dict:
        root = workspace_root()
        if not root.is_dir():
            result = f"Agent workspace {root} does not exist yet — no generated projects to review."
            return {"result": result, "verified": True, "logs": [result]}
        projects = sorted(p for p in root.iterdir() if p.is_dir())
        if not projects:
            result = f"Agent workspace {root} is empty — no generated projects to review."
            return {"result": result, "verified": True, "logs": [result]}
        lines = [f"Found {len(projects)} generated project(s) in {root}:"]
        for proj in projects:
            files = sorted(f for f in proj.iterdir() if f.is_file())
            title = ""
            index = proj / "index.html"
            if index.is_file():
                m = re.search(r"<title>(.*?)</title>", index.read_text(encoding="utf-8", errors="ignore"), re.IGNORECASE)
                title = m.group(1) if m else ""
            listing = ", ".join(f"{f.name} ({f.stat().st_size} B)" for f in files)
            lines.append(f"- {proj.name}: {listing}" + (f" — title: '{title}'" if title else ""))
        result = "\n".join(lines)
        return {"result": result, "verified": True, "logs": [f"Reviewed {len(projects)} project dir(s) on disk."]}
